# ── The command ──────────────────────────────────────────────────────────────

def test_nothing_secret_is_ever_an_argument():
    """The reason the key travels by SFTP. A command's arguments are visible in `ps` while it
    runs and are kept in the stored output of the run."""
    _c, key, _k = make_cert()
    cmd = ci.build_install_command("/etc/nginx/x.conf", "shop.com")
    assert "PRIVATE KEY" not in cmd
    assert key.splitlines()[1] not in cmd


