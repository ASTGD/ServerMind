"""Installing a certificate the customer already has — Ploi's "install existing certificate".

Every certificate here is a REAL one, generated by `cryptography` in the test. A hand-written
PEM fixture proves that our parser accepts the fixture; only a real key pair proves that the
match check would catch a mismatched one.

The two refusals that matter both happen before the server is touched, and both are things
that look fine on screen and break the machine:

* a key that does not belong to the certificate makes nginx **refuse to start**, which on a
  shared server takes down every site on it — not only this one;
* a certificate for the wrong domain gives every visitor a name warning, which is worse than
  no HTTPS because the padlock says it was handled.
"""
import datetime as dt

import pytest
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

from app.services import cert_install_service as ci


def make_cert(common="shop.com", sans=("shop.com",), days=90, start_days=-1, ca=False,
              issuer_name=None, key=None):
    """A real certificate and its real key."""
    key = key or rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, common)])
    issuer = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, issuer_name or common)])
    now = dt.datetime.now(dt.timezone.utc)
    builder = (
        x509.CertificateBuilder()
        .subject_name(subject).issuer_name(issuer)
        .public_key(key.public_key()).serial_number(x509.random_serial_number())
        .not_valid_before(now + dt.timedelta(days=start_days))
        .not_valid_after(now + dt.timedelta(days=days))
    )
    if sans:
        builder = builder.add_extension(
            x509.SubjectAlternativeName([x509.DNSName(n) for n in sans]), critical=False)
    if ca:
        builder = builder.add_extension(x509.BasicConstraints(ca=True, path_length=None),
                                        critical=True)
    cert = builder.sign(key, hashes.SHA256())
    return (cert.public_bytes(serialization.Encoding.PEM).decode(),
            key.private_bytes(serialization.Encoding.PEM,
                              serialization.PrivateFormat.PKCS8,
                              serialization.NoEncryption()).decode(),
            key)


# ── The two refusals that protect the machine ────────────────────────────────

def test_a_key_from_a_different_certificate_is_refused():
    """The one that takes the whole web server down. nginx will not start with a mismatched
    pair, so on a shared box every OTHER site goes with it."""
    cert, _key, _k = make_cert()
    _c2, other_key, _k2 = make_cert()
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, other_key, "shop.com")
    assert "does not belong" in str(exc.value)


def test_the_matching_pair_is_accepted():
    cert, key, _k = make_cert()
    out = ci.check(cert, key, "shop.com")
    assert out["names"] == ["shop.com"]
    assert out["days_left"] > 80


def test_a_certificate_for_another_domain_is_refused():
    """Installing it would show a warning to every visitor — worse than no HTTPS, because
    it looks handled."""
    cert, key, _k = make_cert(common="other.com", sans=("other.com",))
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, key, "shop.com")
    assert "other.com" in str(exc.value) and "shop.com" in str(exc.value)


# ── Wildcards, exactly as a browser reads them ───────────────────────────────

@pytest.mark.parametrize("names,domain,expected", [
    (["*.shop.com"], "www.shop.com", True),
    (["*.shop.com"], "shop.com", False),          # a wildcard does NOT cover the bare name
    (["*.shop.com"], "a.b.shop.com", False),      # …nor two labels deep
    (["shop.com", "*.shop.com"], "shop.com", True),
    (["*.shop.com"], "www.shop.com.evil.com", False),
    (["shop.com"], "SHOP.COM", True),             # case is not part of a hostname
    ([], "shop.com", False),
])
def test_wildcard_matching_is_no_more_generous_than_a_browser(names, domain, expected):
    """Being generous here means installing a certificate browsers then reject — the failure
    lands on the visitor, not on us."""
    assert ci.covers(names, domain) is expected


def test_a_wildcard_certificate_installs_on_a_subdomain():
    cert, key, _k = make_cert(common="*.shop.com", sans=("*.shop.com",))
    assert ci.check(cert, key, "www.shop.com")["names"] == ["*.shop.com"]


# ── Dates ────────────────────────────────────────────────────────────────────

def test_an_expired_certificate_is_refused():
    """Strictly worse than none: the browser refuses the page outright instead of marking
    it insecure."""
    cert, key, _k = make_cert(days=-1, start_days=-30)
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, key, "shop.com")
    assert "expired" in str(exc.value)


def test_a_certificate_that_is_not_valid_yet_is_refused():
    cert, key, _k = make_cert(days=90, start_days=5)
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, key, "shop.com")
    assert "not valid until" in str(exc.value)


# ── What people actually paste ───────────────────────────────────────────────

def test_the_certificate_pasted_into_the_key_box_is_named_precisely():
    """The single most likely mistake. "Could not be read" would send somebody looking at
    the wrong file."""
    cert, _key, _k = make_cert()
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, cert, "shop.com")
    assert "not a private key" in str(exc.value)


def test_a_passphrase_protected_key_is_refused_with_the_way_out():
    """nginx cannot be asked for a passphrase when it starts, so the server simply never
    comes up — a failure with no visible cause."""
    _c, _k, key = make_cert()
    locked = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
        serialization.BestAvailableEncryption(b"secret")).decode()
    cert, _plain, _kk = make_cert(key=key)
    with pytest.raises(ci.CertError) as exc:
        ci.check(cert, locked, "shop.com")
    assert "passphrase" in str(exc.value) and "openssl" in str(exc.value)


def test_rubbish_is_refused_before_anything_happens():
    with pytest.raises(ci.CertError):
        ci.check("hello", "world", "shop.com")


def test_a_chain_pasted_in_the_wrong_order_is_put_right():
    """Leaf-then-intermediate is what nginx wants. The other way round produces a
    certificate some devices accept and others reject — the worst kind to diagnose."""
    ca_pem, _ca_key, _k = make_cert(common="Test CA", sans=(), ca=True)
    leaf_pem, _key, _k2 = make_cert(issuer_name="Test CA")
    fixed = ci.normalise_chain(ca_pem + leaf_pem)
    assert fixed.count("BEGIN CERTIFICATE") == 2, "nothing may be dropped"
    first = x509.load_pem_x509_certificate(
        (fixed.split("-----END CERTIFICATE-----")[0] + "-----END CERTIFICATE-----\n").encode())
    assert first.subject.rfc4514_string() == "CN=shop.com", "the leaf must come first"


def test_a_self_signed_certificate_is_reported_not_refused():
    """A Cloudflare origin certificate is self-signed as far as a public root store is
    concerned, and it is a perfectly good thing to install."""
    cert, key, _k = make_cert()
    assert ci.check(cert, key, "shop.com")["self_signed"] is True


