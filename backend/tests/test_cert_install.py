def test_success_is_judged_on_content_not_a_status_code():
    """A site can answer 200 with a blank body. A certificate "installed" onto a page that
    serves nothing is not a success."""
    cmd = ci.build_install_command("/etc/nginx/x.conf", "shop.com")
    assert 'BODY=$(curl' in cmd and '[ -z "$BODY" ]' in cmd


def test_a_site_that_was_already_broken_keeps_the_certificate():
    """Found in the WordPress switches and it applies here too: rolling back on a
    pre-existing outage leaves somebody unable to install a certificate at exactly the moment
    they are fixing the site."""
    cmd = ci.build_install_command("/etc/nginx/x.conf", "shop.com")
    assert "WAS=$(curl" in cmd
    assert cmd.index("WAS=$(curl") < cmd.index('cp -p "$CFG" "$BAK"'), (
        "the before-state has to be read BEFORE the change")
    assert "OK-BROKEN" in cmd


# ── What the customer reads ──────────────────────────────────────────────────

@pytest.mark.parametrize("code,out,ok,says", [
    (0, ">>> OK: 200", True, "installed"),
    (0, ">>> OK-BROKEN: 500", True, "already not"),
    (1, ">>> ERROR: the web server refused the new configuration", False, "refused"),
    (1, ">>> ERROR: the site stopped serving after the change", False, "put back"),
    (1, "no listener to add HTTPS to", False, "hand-written"),
    (1, "some unrelated noise", False, "nothing was changed"),
])
def test_the_message_is_ours_and_never_the_script_s_last_line(code, out, ok, says):
    got_ok, message = ci.explain(code, out)
    assert got_ok is ok
    assert says in message


# ── Run it, do not read it ───────────────────────────────────────────────────
#
# Everything below EXECUTES the generated script with the web server and curl replaced by
# stubs. The first test here exists because the first version of this module had a bug that
# reading it did not reveal: the insertion matched both `listen 80;` and `listen [::]:80;`,
# so nginx got a duplicate listener and refused to start — for every site on the machine.

import subprocess


NGINX_PLAIN = """\
server {
    listen 80;
    listen [::]:80;
    server_name shop.com;
    root /var/www/shop;
}
"""

NGINX_HTTPS = """\
server {
    listen 80;
    server_name shop.com;
    return 301 https://$host$request_uri;
}
server {
    listen 443 ssl;
    server_name shop.com;
    ssl_certificate     /etc/letsencrypt/live/shop.com/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/shop.com/privkey.pem;
    root /var/www/shop;
}
"""


def run_script(tmp_path, config: str, *, accepts=True, code="200", body="THE REAL SHOP",
               before="200"):
    """Run the real generated command with stubbed nginx/systemctl/curl."""
    binstub = tmp_path / "bin"
    binstub.mkdir(exist_ok=True)
    (binstub / "nginx").write_text(
        "#!/bin/sh\n" + ("exit 0\n" if accepts else "echo 'nginx: [emerg] bad' >&2; exit 1\n"))
    (binstub / "systemctl").write_text("#!/bin/sh\nexit 0\n")
    # Two curl shapes are used: one asks for the body, one asks only for the status code.
    # `WAS` (the before-state) is read first, so the stub answers that one differently.
    (binstub / "curl").write_text(
        "#!/bin/sh\n"
        'if [ -f /tmp/sa_seen ]; then C="' + code + '"; else C="' + before + '"; touch /tmp/sa_seen; fi\n'
        'case "$*" in\n'
        '  *-w*) printf "%s" "$C" ;;\n'
        '  *) printf "%s" "' + body + '" ;;\n'
        "esac\n")
    for f in ("nginx", "systemctl", "curl"):
        (binstub / f).chmod(0o755)

    cfg = tmp_path / "shop.conf"
    cfg.write_text(config)
    ssl_dir = tmp_path / "ssl"
    ssl_dir.mkdir(exist_ok=True)

    cmd = ci.build_install_command(str(cfg), "shop.com")
    # Point the real paths at the temporary directory, and create the incoming files the way
    # SFTP would have.
    cmd = cmd.replace("/etc/ssl/serverally/shop.com", str(ssl_dir))
    (ssl_dir / "fullchain.pem.new").write_text("NEW-CERT\n")
    (ssl_dir / "privkey.pem.new").write_text("NEW-KEY\n")

    proc = subprocess.run(
        ["bash", "-c", f'rm -f /tmp/sa_seen; export PATH="{binstub}:$PATH"; {cmd}'],
        capture_output=True, text=True)
    return proc.returncode, cfg.read_text(), proc.stdout + proc.stderr, ssl_dir


def test_https_is_added_once_per_block_not_once_per_listen_line(tmp_path):
    """The bug that only running it revealed. An ordinary vhost has BOTH `listen 80;` and
    `listen [::]:80;`; inserting after each gives nginx a duplicate 443 listener, and nginx
    then refuses to start — taking down every site on the machine, not just this one."""
    code, text, out, _ssl = run_script(tmp_path, NGINX_PLAIN)
    assert code == 0, out
    assert text.count("listen 443 ssl;") == 1, text
    assert text.count("listen [::]:443 ssl;") == 1, text
    assert text.count("ssl_certificate ") == 1


def test_a_site_that_already_has_https_is_repointed_in_every_block(tmp_path):
    """A site whose http and https halves use different certificates is a bug nobody can see
    from one screen — and no new listener may be added, or nginx refuses to start."""
    code, text, out, ssl_dir = run_script(tmp_path, NGINX_HTTPS)
    assert code == 0, out
    assert "letsencrypt" not in text
    assert text.count(f"ssl_certificate {ssl_dir}/fullchain.pem;") == 1
    assert text.count("listen 443 ssl;") == 1, "an existing listener must not be duplicated"


def test_a_refused_configuration_changes_nothing(tmp_path):
    """A configuration that does not parse does not break one site — the reload fails for
    the whole machine, so the file must go back exactly as it was."""
    code, text, out, ssl_dir = run_script(tmp_path, NGINX_PLAIN, accepts=False)
    assert code == 1
    assert text == NGINX_PLAIN, "the configuration must be byte-identical"
    assert "refused the new configuration" in out
    assert not list(ssl_dir.glob("*.prev")), "no leftovers"


def test_a_refused_configuration_puts_the_previous_certificate_back(tmp_path):
    """Replacing a certificate overwrites the live files BEFORE the config is known to be
    good. Without putting them back, a refused change leaves the running site pointing at a
    file we swapped underneath it."""
    ssl_dir = tmp_path / "ssl"
    ssl_dir.mkdir()
    (ssl_dir / "fullchain.pem").write_text("OLD-CERT\n")
    (ssl_dir / "privkey.pem").write_text("OLD-KEY\n")
    code, _text, out, _s = run_script(tmp_path, NGINX_HTTPS, accepts=False)
    assert code == 1, out
    assert (ssl_dir / "fullchain.pem").read_text() == "OLD-CERT\n"
    assert (ssl_dir / "privkey.pem").read_text() == "OLD-KEY\n"


def test_a_blank_page_after_the_change_is_a_failure(tmp_path):
    """200 is not proof. A certificate installed onto a page that serves nothing is not a
    success, and the config goes back."""
    code, text, out, _s = run_script(tmp_path, NGINX_PLAIN, body="")
    assert code == 1
    assert text == NGINX_PLAIN
    assert "stopped serving" in out


def test_a_site_that_was_already_down_keeps_the_certificate(tmp_path):
    """Rolling back on a pre-existing outage would leave somebody unable to install a
    certificate at exactly the moment they are fixing the site."""
    code, text, out, _s = run_script(tmp_path, NGINX_PLAIN, before="500", code="500", body="")
    assert code == 0, out
    assert "OK-BROKEN" in out
    assert "listen 443 ssl;" in text, "the certificate stays in place"


def test_a_configuration_with_no_plain_listener_is_refused_honestly(tmp_path):
    """A hand-written vhost we cannot safely extend gets a message naming the way forward,
    not a silent no-op that looks like success."""
    code, _text, out, _s = run_script(tmp_path, "server {\n    listen 8080;\n}\n")
    assert code == 1
    assert "no listener to add HTTPS to" in out
    assert ci.explain(code, out) == (False, ci.explain(code, out)[1])
    assert "hand-written" in ci.explain(code, out)[1]


def test_the_key_really_ends_up_readable_by_root_only(tmp_path):
    import os
    import stat

    _code, _text, _out, ssl_dir = run_script(tmp_path, NGINX_PLAIN)
    mode = stat.S_IMODE(os.stat(ssl_dir / "privkey.pem").st_mode)
    assert mode == 0o600, oct(mode)
    assert stat.S_IMODE(os.stat(ssl_dir / "fullchain.pem").st_mode) == 0o644


def test_the_directory_is_made_before_the_upload_and_kept_shut(tmp_path):
    """SFTP does not create parent directories, so a site's FIRST certificate would fail to
    upload at all. And 700 rather than 755 both here and in the install: the web server reads
    the key as root before dropping privileges, so nothing else needs to get in."""
    prep = ci.build_prepare_command("shop.com")
    assert "install -d -m 700" in prep
    assert "/etc/ssl/serverally/shop.com" in prep
    assert "-m 755" not in ci.build_install_command("/etc/nginx/x.conf", "shop.com")


